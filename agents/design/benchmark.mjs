#!/usr/bin/env node
/**
 * Build-time benchmark against the spec's ~10 s per-site target (System 04 section 1).
 *   node agents/design/benchmark.mjs [--out <scratch dir>] [--write]      (--write updates BENCHMARKS.md)
 * Measures render only (resolve + astro build + inline CSS), not QA; then the QA checks separately.
 * Sequential first (cold then warm), then parallel at 2 / 4 / 8 workers over the same 20 sites.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { join, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import os from "node:os";
import { makeClient, VERTICAL_IDS } from "./fixtures.mjs";
import { renderSite, renderMany } from "./design-agent.mjs";
import { runWithQa } from "./qa-loop.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);
const opt = (n, d) => { const i = args.indexOf(n); return i >= 0 ? args[i + 1] : d; };
const out = resolve(opt("--out", join(HERE, "out/bench")));
mkdirSync(out, { recursive: true });

const sites = VERTICAL_IDS.flatMap((v) => ["smb", "micro"].flatMap((tier) => ["professional-service", "energetic-bold", "eco-conscious"].slice(0, tier === "smb" ? 3 : 2).map((profile) => makeClient({ vertical: v, tier, profile }))));
const stat = (xs) => { const s = [...xs].sort((a, b) => a - b); const q = (p) => s[Math.min(s.length - 1, Math.floor(p * s.length))]; return { n: s.length, mean: Math.round(s.reduce((a, b) => a + b, 0) / s.length), p50: q(0.5), p95: q(0.95), max: s.at(-1) }; };
const sec = (ms) => (ms / 1000).toFixed(2) + " s";
const rows = [];

// sequential: the first build of the run may pay one-off costs (module graph, disk cache); the rest are warm
const seq = [];
for (const c of sites) { const r = await renderSite(c, { outDir: join(out, "seq", c.slug) }); if (!r.ok) throw new Error(`${c.slug}: ${r.error}`); seq.push(r.ms); }
const cold = seq[0].total;
const warm = stat(seq.slice(1).map((m) => m.total));
const build = stat(seq.slice(1).map((m) => m.build));
const inline = stat(seq.slice(1).map((m) => m.inline));

const par = [];
for (const k of [2, 4, 8]) {
  const t0 = performance.now();
  const rs = await renderMany(sites, { outRoot: join(out, `par${k}`), concurrency: k });
  const wall = Math.round(performance.now() - t0);
  if (rs.some((r) => !r.ok)) throw new Error(`parallel ${k}: ${rs.find((r) => !r.ok).error}`);
  par.push({ k, wall, perSite: Math.round(wall / sites.length), each: stat(rs.map((r) => r.ms.total)) });
}

// QA (non-browser checks) on one built site
const t1 = performance.now();
const qa = await runWithQa(sites[0], { outDir: join(out, "qa", sites[0].slug), browser: "skip", logDir: join(out, "logs") });
const qaMs = Math.round(performance.now() - t1);

const fastest = Math.min(...par.map((p) => p.wall));
const best = par.find((p) => p.wall <= fastest * 1.05);
const seqTotal = seq.reduce((a, m) => a + m.total, 0);
const md = `${`---
title: Design Agent build benchmarks
purpose: Per-site build time of the deterministic Design Agent against the spec's ~10 s target, sequential and parallel
status: active
owner: c.t.cohen
updated: '${new Date().toISOString().slice(0, 10)}'
version: 1.0.0
tier_scope: all
phase: phase_1
---`}

# Design Agent build benchmarks

Generated by \`node agents/design/benchmark.mjs --write\`. ${sites.length} sites (4 verticals x SMB and Micro x 2-3 profiles), fictional data from \`fixtures.mjs\`.
Machine: ${os.cpus()[0].model}, ${os.cpus().length} cores, ${(os.totalmem() / 2 ** 30).toFixed(0)} GB, Node ${process.version}, Astro build (static output, CSS inlined). No LLM call, so no token cost.

**Target (System 04 section 1): about 10 s per site. Result: ${sec(warm.max)} worst case sequential, ${sec(warm.mean)} average. About ${(10000 / warm.mean).toFixed(0)}x inside the target.**

## Sequential (one build at a time)
| | time |
|---|---|
| First build of the run | ${sec(cold)} |
| Warm mean / p50 / p95 / max (n=${warm.n}) | ${sec(warm.mean)} / ${sec(warm.p50)} / ${sec(warm.p95)} / ${sec(warm.max)} |
| of which Astro build (mean) | ${sec(build.mean)} |
| of which CSS inlining (mean) | ${sec(inline.mean)} |
| All ${sites.length} sites | ${sec(seqTotal)} |

## Parallel (each build in its own work root, so Astro's mutable state does not collide)
| Workers | Wall time for ${sites.length} sites | Per site (wall / n) | Single build under load (mean / p95) |
|---|---|---|---|
${par.map((p) => `| ${p.k} | ${sec(p.wall)} | ${sec(p.perSite)} | ${sec(p.each.mean)} / ${sec(p.each.p95)} |`).join("\n")}

Sequential baseline for the same set: ${sec(seqTotal)} (${sec(seqTotal / sites.length)} per site).

## QA (deterministic checks, no browser)
Render plus schema, build, placeholder, required-content, link and contrast checks for one site: ${sec(qaMs)}. Lighthouse and layout checks need Chrome and a local port; they run on Tyler's machine (not measurable in this sandbox).

## Findings
- Rendering is dominated by Astro's build (~${Math.round((build.mean / warm.mean) * 100)}% of the time); resolving the design and inlining CSS are negligible.
- Parallel builds work because each build gets a private root (\`.work-<slug>/\`) and a private Vite cache. Sharing one root fails with an Astro data-store write race.
- Throughput flattens after ${best.k} workers on this machine (${par.map((p) => `${p.k}: ${sec(p.wall)}`).join(", ")}); default to ${best.k}, since more workers only slow each individual build.
- The spec's per-site target is met with wide margin even sequentially, so parallelism matters for batch runs (nightly demo generation), not for a single demo.
`;
console.log(md.split("\n").slice(12).join("\n"));
if (args.includes("--write")) writeFileSync(join(HERE, "BENCHMARKS.md"), md);
